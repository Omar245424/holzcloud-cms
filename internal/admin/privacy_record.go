// The record of processing activities of a website (Phase 33.2, DSR-05,
// D-02): on the screen under Settings → Privacy, as a page to print or save
// as a PDF, and as a JSON file.
//
// The record is generated by dsr.BuildRecord from what the website uses, the
// frameworks it follows and the periods it keeps; nothing is stored, so there
// is nothing to edit here and nothing that can fall behind the settings. What
// the CMS cannot know is marked as to be filled in, and the operator fills it
// in on the printed copy or in the JSON.
//
// The record holds no person's data, so everybody with access to the website
// may read it, like the Retention screen; RequireWebsiteAccess guards the
// path.

// recordBackupDays is how long the nightly backups are kept: RETENTION_DAYS
// of deploy/backup.sh, 30 unless the operator changed the unit. The program
// cannot read the unit, so the record says the default.
const recordBackupDays = 30

// recordControllerRows are the controller's details in the order the record
// shows them, each with its label, a catalogue key.
var recordControllerRows = []struct{ Key, Label string }{
	{"name", i18n.N("Name")},
	{"street", i18n.N("Street")},
	{"postal_code", i18n.N("Postcode")},
	{"city", i18n.N("Town")},
	{"country", i18n.N("Country")},
	{"email", i18n.N("E-mail address")},
	{"phone", i18n.N("Telephone")},
	{"representative", i18n.N("Representative")},
	{"data_protection_officer", i18n.N("Data protection officer")},
}

// recordRow is one line of the controller block.
type recordRow struct {
	// Label is a catalogue key, Value the text as the record has it.
	Label, Value string
}

// privacyRecordData backs the screen and the print page.
type privacyRecordData struct {
	web.LayoutData
	WebsiteID   int64
	WebsiteName string
	Record      dsr.ProcessingRecord
	Controller  []recordRow
	// Generated is when the record was generated, on the website's clock.
	Generated string
	// ScreenURL, PrintURL and JSONURL are the three forms of the record.
	ScreenURL, PrintURL, JSONURL string
}

// privacyRecordAddress is the screen of one website.
func privacyRecordAddress(websiteID int64) string {
	return privacyAddress(websiteID) + "/verzeichnis"
}

// recordInput is everything the record of a website is generated from, in
// one place for the screen, the JSON, the access export and the assistant's
// tool, so the four can never describe the website differently.
func (h *Handler) recordInput(ctx context.Context, ws *domain.Website, lang string) (dsr.RecordInput, error) {
	in := dsr.RecordInput{
		WebsiteID:  ws.ID,
		Name:       ws.Name,
		Street:     ws.Street,
		PostalCode: ws.PostalCode,
		City:       ws.City,
		Country:    ws.Country,
		Email:      ws.ContactEmail,
		Phone:      ws.Phone,
		Set:        ws.Frameworks(),
		LogDays:    web.LogRetentionDays,
		BackupDays: recordBackupDays,
		Lang:       lang,
		Now:        time.Now(),
	}
	features, err := h.privacyFeatures(ctx, ws)
	if err != nil {
		return in, err
	}
	in.Features = features
	if in.Holders, err = h.dataRights.Holders(ctx, ws.ID); err != nil {
		return in, err
	}
	if in.Periods, err = h.dataRights.Periods(ctx, ws.ID, ws.Country); err != nil {
		return in, err
	}
	if in.OrderYears, in.OrderPeriod, err = h.dataRights.OrderYears(ctx, ws.ID, ws.Country); err != nil {
		return in, err
	}
	if in.AccountMonths, err = h.dataRights.AccountMonths(ctx); err != nil {
		return in, err
	}
	in.MailConfigured = h.mail.EnabledFor(ctx, ws.ID)
	return in, nil
}

// privacyRecord builds the record of the website of the path in the
// operator's language, with what the screen and the print page show around
// it.
func (h *Handler) privacyRecord(r *http.Request, ws *domain.Website) (*privacyRecordData, error) {
	ctx := r.Context()
	in, err := h.recordInput(ctx, ws, i18n.Lang(ctx))
	if err != nil {
		return nil, err
	}
	rec := dsr.BuildRecord(in)
	base := privacyRecordAddress(ws.ID)
	data := &privacyRecordData{
		LayoutData:  web.NewLayoutData(r, h.sm, web.Titlef(r, "Record of processing – %s", ws.Name)),
		WebsiteID:   ws.ID,
		WebsiteName: ws.Name,
		Record:      rec,
		Generated:   in.Now.In(tmpl.LoadLocation(ws.TimeZone)).Format("02.01.2006 15:04 MST"),
		ScreenURL:   base,
		PrintURL:    base + "/drucken",
		JSONURL:     base + ".json",
	}
	for _, row := range recordControllerRows {
		data.Controller = append(data.Controller, recordRow{Label: row.Label, Value: rec.Controller[row.Key]})
	}
	data.ActiveNav = "privacy-record"
	data.CurrentWebsite = ws
	return data, nil
}

// HandlePrivacyRecord shows the record of processing activities of a
// website.
func (h *Handler) HandlePrivacyRecord(w http.ResponseWriter, r *http.Request) error {
	ws, ok, err := h.privacyWebsite(w, r)
	if err != nil || !ok {
		return err
	}
	data, err := h.privacyRecord(r, ws)
	if err != nil {
		return err
	}
	return web.RenderAdmin(w, h.templates, r, "privacy_record", data)
}

// HandlePrivacyRecordPrint shows the record as a sheet of its own, to print
// or to save as a PDF from the browser (D-02: no PDF library).
func (h *Handler) HandlePrivacyRecordPrint(w http.ResponseWriter, r *http.Request) error {
	ws, ok, err := h.privacyWebsite(w, r)
	if err != nil || !ok {
		return err
	}
	data, err := h.privacyRecord(r, ws)
	if err != nil {
		return err
	}
	// A standalone page has no fragment to answer an htmx request with.
	r.Header.Del("HX-Request")
	return web.RenderAdmin(w, h.templates, r, "privacy_record_print", data)
}

// websiteLang is the language an answer to a person is written in: the
// website's main language, as the person read the website. Spanish reads
// English, because there are no Spanish legal texts (33.1 D-16) and the
// rights in the answer must say what the published notice says; a language
// this build has no catalogue for reads English too.
func websiteLang(ws *domain.Website) string {
	tag := i18n.Normalise(ws.Locale)
	base := i18n.Base(tag)
	if base == "" {
		base = tag
	}
	switch {
	case tag == "" || base == "es":
		return i18n.Source
	case i18n.Known(tag):
		return tag
	case i18n.Known(base):
		return base
	}
	return i18n.Source
}

// privacyAnswerAddress is the printable answer of one website.
func privacyAnswerAddress(websiteID int64) string {
	return privacyAddress(websiteID) + "/auskunft"
}

// privacyAnswerResult is one answer to an access request: what was found
// under the address, and the record of processing that describes it, both
// in the website's language.
type privacyAnswerResult struct {
	Lang   string
	Result *dsr.Result
	Input  dsr.RecordInput
	Record dsr.ProcessingRecord
	Export dsr.Export
	Now    time.Time
}

// privacyAnswer finds what the website holds under ?email= and describes it
// with the website's record of processing. The search runs in the website's
// language too, so a plugin labels its fields for the person and not for
// the operator. An invalid address is dsr.ErrBadEmail.
func (h *Handler) privacyAnswer(r *http.Request, ws *domain.Website) (*privacyAnswerResult, error) {
	lang := websiteLang(ws)
	ctx := i18n.WithLang(r.Context(), lang)
	res, err := h.dataRights.FindFor(ctx, ws.ID, r.URL.Query().Get("email"), h.isAdmin(r))
	if err != nil {
		return nil, err
	}
	in, err := h.recordInput(ctx, ws, lang)
	if err != nil {
		return nil, err
	}
	rec := dsr.BuildRecord(in)
	exp := dsr.BuildExport(res, ws.ID, ws.Name, in.Now)
	exp.Describe(rec)
	return &privacyAnswerResult{Lang: lang, Result: res, Input: in, Record: rec, Export: exp, Now: in.Now}, nil
}

// answerKept is a record that was reduced at an erasure and stays until its
// period ends.
type answerKept struct {
	// Label is a catalogue key.
	Label, Key string
	// Until is the date the record may be deleted, "" when it is not an
	// order.
	Until string
}

// privacyAnswerData backs the printable answer.
type privacyAnswerData struct {
	web.LayoutData
	WebsiteName string
	Email       string
	// AsOf is the date of the answer, on the website's clock.
	AsOf       string
	Controller []recordRow
	Count      int
	Groups     []privacyGroup
	Categories []dsr.ExportCategory
	Rights     []dsr.ExportRight
	Kept       []answerKept
	// NotCovered and Failed tell the operator, on the screen only, that the
	// answer may be incomplete.
	NotCovered []dsr.Holder
	Failed     bool
	BackURL    string
}

// HandlePrivacyAnswerPrint shows the answer to an access request for
// ?email= as a sheet to print or save as a PDF and hand to the person
// (D-02): the same records and the same description as the JSON file, in
// the website's language. It is a person's data, so it is never cached,
// and handing it out is logged like the JSON download, without the
// address.
func (h *Handler) HandlePrivacyAnswerPrint(w http.ResponseWriter, r *http.Request) error {
	ws, ok, err := h.privacyWebsite(w, r)
	if err != nil || !ok {
		return err
	}
	ans, err := h.privacyAnswer(r, ws)
	if errors.Is(err, dsr.ErrBadEmail) {
		w.WriteHeader(http.StatusBadRequest)
		return nil
	}
	if err != nil {
		return err
	}
	r = r.WithContext(i18n.WithLang(r.Context(), ans.Lang))
	loc := tmpl.LoadLocation(ws.TimeZone)
	data := &privacyAnswerData{
		LayoutData:  web.NewLayoutData(r, h.sm, web.Titlef(r, "Information about your personal data – %s", ws.Name)),
		WebsiteName: ws.Name,
		Email:       ans.Result.Email,
		AsOf:        ans.Now.In(loc).Format("02.01.2006"),
		Count:       len(ans.Result.Records),
		Groups:      privacyGroups(ans.Result, loc),
		Categories:  ans.Export.Categories,
		Rights:      ans.Export.Rights,
		NotCovered:  ans.Result.NotCovered(),
		Failed:      len(ans.Result.Failed) > 0,
		BackURL:     privacyAddress(ws.ID) + "?email=" + url.QueryEscape(ans.Result.Email),
	}
	for _, row := range recordControllerRows {
		data.Controller = append(data.Controller, recordRow{Label: row.Label, Value: ans.Record.Controller[row.Key]})
	}
	for _, rec := range ans.Result.Records {
		if !rec.Erased {
			continue
		}
		k := answerKept{Label: rec.Label, Key: rec.Key}
		if rec.Kind == dsr.RetentionOrder && !rec.Time.IsZero() {
			k.Until = legal.OrderDeletableFrom(rec.Time, ans.Input.OrderYears).In(loc).Format("02.01.2006")
		}
		data.Kept = append(data.Kept, k)
	}
	w.Header().Set("Cache-Control", "no-store")
	r.Header.Del("HX-Request")
	if err := web.RenderAdmin(w, h.templates, r, "privacy_answer_print", data); err != nil {
		return err
	}
	websiteID := ws.ID
	h.LogActivity(r, activity.Entry{
		Action:     activity.ActionPrivacyExport,
		EntityType: "website",
		EntityID:   ws.ID,
		WebsiteID:  &websiteID,
		Metadata:   map[string]any{"records": len(ans.Result.Records), "format": "print"},
	})
	return nil
}

// HandlePrivacyRecordJSON answers with the record as a JSON file.
func (h *Handler) HandlePrivacyRecordJSON(w http.ResponseWriter, r *http.Request) error {
	ws, ok, err := h.privacyWebsite(w, r)
	if err != nil || !ok {
		return err
	}
	in, err := h.recordInput(r.Context(), ws, i18n.Lang(r.Context()))
	if err != nil {
		return err
	}
	body, err := json.MarshalIndent(dsr.BuildRecord(in), "", "  ")
	if err != nil {
		return err
	}
	name := "record-of-processing-" + strconv.FormatInt(ws.ID, 10) + "-" + in.Now.UTC().Format("2006-01-02") + ".json"
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.Header().Set("Content-Disposition", `attachment; filename="`+name+`"`)
	// The record describes the website's settings at this moment; a cached
	// copy would describe them as they were.
	w.Header().Set("Cache-Control", "no-store")
	_, _ = w.Write(append(body, '\n'))
	return nil
}
